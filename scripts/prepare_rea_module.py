#!/usr/bin/env python3
"""Prepare a private OS-9 Prog image for REA/Ghidra without changing media.

The analysis image prepends a synthetic JMP and padding. The complete module
is preserved at offset 0x100; this image must never be used by the runtime.
Only explicitly supplied contiguous Form 1 extents are supported, not a full
filesystem extractor. Generated bytes and detailed metadata remain private.
"""

import argparse
import functools
import hashlib
import json
from pathlib import Path
import struct
import sys

from verify_local_media import check_sector, parse_cue, read_sector, sha256_file


ROOT = Path(__file__).resolve().parents[1]
MODULE_BASE = 0x100
MAX_MODULE_BYTES = 16 * 1024 * 1024
MAX_TARGETS = 32768
CRC_MASK = (1 << 24) - 1
CRC_POLYNOMIAL = 0x800063


@functools.lru_cache(maxsize=1)
def crc_table():
    """Remainders of x^24 byte terms over GF(2), polynomial 0x800063."""
    table = []
    for byte in range(256):
        remainder = byte << 16
        for _ in range(8):
            high = remainder & (1 << 23)
            remainder = (remainder << 1) & CRC_MASK
            if high:
                remainder ^= CRC_POLYNOMIAL
        table.append(remainder)
    return tuple(table)


def crc24(data):
    remainder = CRC_MASK
    table = crc_table()
    for byte in data:
        remainder = ((remainder << 8) & CRC_MASK) ^ table[(remainder >> 16) ^ byte]
    return remainder


def integer(value, name, minimum, maximum):
    if isinstance(value, bool) or not isinstance(value, int) or not minimum <= value <= maximum:
        raise ValueError(f"{name} outside supported integer bounds")
    return value


def inspect_module(data):
    """Validate this narrow OS-9/68000 executable profile, including CRC."""
    if not 0x4B <= len(data) <= MAX_MODULE_BYTES:
        raise ValueError("module size outside supported bounds")
    if data[:2] != b"\x4a\xfc":
        raise ValueError("OS-9 module identifier missing")
    if int.from_bytes(data[4:8], "big") != len(data):
        raise ValueError("declared module size differs from complete input")
    parity = functools.reduce(lambda a, b: a ^ b, struct.unpack_from(">24H", data), 0)
    if parity != 0xFFFF:
        raise ValueError("OS-9 header parity mismatch")
    if data[0x12:0x14] != b"\x01\x01":
        raise ValueError("only OS-9 Prog / 68000 machine-code modules are supported")
    entry, exception = struct.unpack_from(">II", data, 0x30)
    for kind, offset in (("entry", entry), ("exception", exception)):
        if kind == "exception" and offset == 0:
            continue
        if offset < 0x48 or offset >= len(data) - 3 or offset & 1:
            raise ValueError(f"invalid executable {kind} offset")
    if crc24(data) != 0x800FE3:
        raise ValueError("OS-9 module CRC mismatch")
    return {"size": len(data), "sha256": hashlib.sha256(data).hexdigest(),
            "entry_offset": entry, "exception_offset": exception,
            "metadata_end": 0x48, "code_limit_exclusive": len(data) - 3,
            "header_parity_valid": True, "crc_valid": True}


def extract_extent(cue, lba, size):
    """Read only the explicit contiguous range, rejecting unsupported interleave."""
    integer(lba, "LBA", 0, 0xFFFFFFFF)
    integer(size, "size", 0x4B, MAX_MODULE_BYTES)
    image = parse_cue(cue)
    image_size = image.stat().st_size
    count = (size + 2047) // 2048
    if image_size % 2352 or (lba + count) * 2352 > image_size:
        raise ValueError("explicit extent exceeds complete raw image")
    payload = bytearray()
    identity = None
    with image.open("rb") as stream:
        for current in range(lba, lba + count):
            sector = read_sector(stream, current)
            if check_sector(sector, current) != 1:
                raise ValueError("explicit extent includes unsupported Form 2 sector")
            if identity is None:
                identity = sector[16:18]
            if sector[16:18] != identity:
                raise ValueError("file/channel changes inside explicit extent")
            if sector[18] & 0x80 and current != lba + count - 1:
                raise ValueError("EOF before end of explicit extent")
            payload.extend(sector[24:2072])
    return bytes(payload[:size]), {
        "kind": "explicit-contiguous-form1-extent", "cue": str(cue.resolve()),
        "image": str(image.resolve()), "image_size": image_size,
        "image_sha256": sha256_file(image), "cue_sha256": sha256_file(cue),
        "lba": lba, "requested_size": size, "sectors_read": count,
        "file_channel": list(identity), "filesystem_membership_verified": False,
        "edc_ecc_checked": False}


def analysis_image(data):
    info = inspect_module(data)
    stub = b"\x4e\xf9" + struct.pack(">I", MODULE_BASE + info["entry_offset"])
    return stub.ljust(MODULE_BASE, b"\0") + data


def observed_seeds(document, info):
    """Convert observed code entries to analysis seeds, never function guesses."""
    registry = document.get("module_targets", document)
    if not isinstance(registry, dict) or not isinstance(registry.get("targets"), list):
        raise ValueError("target registry requires an object with targets array")
    rows = registry["targets"]
    if len(rows) > MAX_TARGETS:
        raise ValueError("target registry exceeds finite limit")
    total = integer(registry.get("total"), "target total", len(rows), MAX_TARGETS)
    dropped = integer(registry.get("dropped"), "target dropped", 0, 2**64 - 1)
    offsets = set()
    duplicates = 0
    other_identity = 0
    for row in rows:
        if not isinstance(row, dict):
            raise ValueError("target row must be an object")
        digest = row.get("sha256")
        if not isinstance(digest, str) or len(digest) != 64:
            raise ValueError("target row requires complete SHA-256 identity")
        try:
            bytes.fromhex(digest)
        except ValueError as exc:
            raise ValueError("invalid target SHA-256 identity") from exc
        if digest.lower() != info["sha256"]:
            other_identity += 1
            continue
        offset = integer(row.get("offset"), "target offset", info["metadata_end"],
                         info["code_limit_exclusive"] - 1)
        if offset & 1:
            raise ValueError("observed code entry is not even aligned")
        integer(row.get("hits"), "target hits", 1, 2**64 - 1)
        if offset in offsets:
            duplicates += 1
        offsets.add(offset)
    if rows and not offsets:
        raise ValueError("no observed targets match this module identity")
    # Historical captures without pagination metadata remain explicitly partial.
    complete = (registry.get("complete") is True and total == len(rows) and dropped == 0)
    return sorted(offsets), {"registry_total": total, "captured_rows": len(rows),
                             "registry_dropped": dropped, "registry_complete": complete,
                             "matching_unique_offsets": len(offsets),
                             "duplicate_offsets": duplicates,
                             "other_identity_rows": other_identity,
                             "seed_kind": "code", "runtime_observation_is_function_proof": False}


def output_destination(output, root=ROOT):
    """Allow only a new private descendant; refuse symlinks and overwrites."""
    root = root.resolve()
    output = Path(output).absolute()
    resolved = output.resolve()
    allowed = (root / "data/private/rea-pilot", root / "build")
    if not any(resolved != base and resolved.is_relative_to(base) for base in allowed):
        raise ValueError("output must be a new directory below data/private/rea-pilot/ or build/")
    for ancestor in (output, *output.parents):
        if ancestor.resolve() == root:
            break
        if ancestor.is_symlink():
            raise ValueError("output path contains a symlink")
    if output.exists():
        raise ValueError("refusing to overwrite existing output directory")
    return resolved


def prepare(data, provenance, output, targets=None, root=ROOT):
    info = inspect_module(data)
    envelope = analysis_image(data)
    seeds = {info["entry_offset"]}
    if info["exception_offset"]:
        seeds.add(info["exception_offset"])
    target_info = None
    if targets is not None:
        observed, target_info = observed_seeds(targets, info)
        seeds.update(observed)
    destination = output_destination(output, root)
    manifest = {"schema_version": 1, "analysis_only": True, "source": provenance,
                "module": info, "module_file": "module.bin",
                "analysis_file": "analysis.bin", "seed_file": "seeds.tsv",
                "analysis_sha256": hashlib.sha256(envelope).hexdigest(),
                "mapping": {"raw_base": 0, "raw_entry": 0, "module_base": MODULE_BASE,
                            "module_offset_from_analysis_address": "address - 0x100",
                            "synthetic_prefix_bytes": MODULE_BASE,
                            "synthetic_entry_jumps_to": MODULE_BASE + info["entry_offset"],
                            "module_preserved_byte_for_byte": True},
                "observed_targets": target_info,
                "limitations": ["Analysis envelope must never be executed by the game runtime.",
                                "Synthetic trampoline is not original game code.",
                                "The 0x100 analysis shift does not relocate absolute address literals.",
                                "Ghidra's m68k language accepts a 68040 instruction superset.",
                                "OS-9 traps/ABI, memory map and hardware are not modeled here.",
                                "Static functions and code seeds do not prove runtime equivalence."]}
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.mkdir()
    outputs = {"module.bin": data, "analysis.bin": envelope,
               "seeds.tsv": ("# Analysis only. Observed entries are code, not proven function boundaries.\n" +
                             "".join(f"0x{MODULE_BASE + off:x}\tcode\n" for off in sorted(seeds))).encode(),
               "manifest.json": (json.dumps(manifest, indent=2) + "\n").encode()}
    for name, content in outputs.items():
        with (destination / name).open("xb") as stream:
            stream.write(content)
    return manifest


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--module", type=Path)
    source.add_argument("--cue", type=Path)
    parser.add_argument("--lba", type=lambda x: int(x, 0))
    parser.add_argument("--size", type=lambda x: int(x, 0))
    parser.add_argument("--targets", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        output_destination(args.output)
        if args.cue:
            if args.lba is None or args.size is None:
                parser.error("--cue requires explicit --lba and --size")
            data, provenance = extract_extent(args.cue, args.lba, args.size)
        else:
            if args.lba is not None or args.size is not None:
                parser.error("--lba/--size require --cue")
            if not 0x4B <= args.module.stat().st_size <= MAX_MODULE_BYTES:
                raise ValueError("module size outside supported bounds")
            data = args.module.read_bytes()
            provenance = {"kind": "complete-module-file", "path": str(args.module.resolve())}
        targets = None
        if args.targets:
            if args.targets.stat().st_size > 32 * 1024 * 1024:
                raise ValueError("target JSON exceeds finite limit")
            targets = json.loads(args.targets.read_text())
            if not isinstance(targets, dict):
                raise ValueError("target JSON must be an object")
        result = prepare(data, provenance, args.output, targets)
    except (OSError, ValueError) as exc:
        parser.exit(2, f"Cannot prepare analysis input: {exc}\n")
    print(f"Private analysis envelope prepared; module bytes preserved ({result['module']['size']} bytes).")
    print("Use REA raw-binary / m68k / entry-point 0x0; analysis addresses include a 0x100 prefix.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
